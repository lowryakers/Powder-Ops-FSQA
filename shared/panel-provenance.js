// Where a nutrition panel's numbers came from (D-128).
//
// A panel was a file, a version label and a set of numbers, and NOTHING said
// which formula produced them. The Apple Pie panel was computed from a
// spreadsheet copy of the formula at a 33.32 g fill while the live BOM said
// 34.86 g and the recipe had since gained flavor, guar gum and MCT oil — and it
// surfaced 1 g of added sugar against a front panel claiming 0 g. Four pancake
// formulas lost their erythritol and their serving size moved while servings
// per container stayed 4.5. In both cases the panel was internally right and
// its link to the formula was stale, and no field could have shown it.
//
// So approval has a gate, and the gate is what it approved AGAINST: a formula
// ref, that formula's version, and the fill weight the values were computed at.
// Everything else here may be blank. A draft may be entirely blank.
//
// ONE OWNER PER FACT. `formula_version` IS `nfp_versions.formula_rev` — the
// column already documented as "which formula the panel was calculated from" —
// not a second copy beside it. The product's CURRENT formula is
// `products.mrp_formula_id` / `products.formula_rev`, the catalogue's own
// pointers; a panel is stale when what it was computed from is not what the
// catalogue now says.
//
// A PANEL WITH NO RECORDED PROVENANCE READS AS UNKNOWN, not as blank:
// `source_system: 'unknown'` and `provenance_missing: true`, derived on every
// read rather than written into the rows. Nothing is backfilled with a guess.
//
// Pure, and in shared/, because the approval gate and the screen that shows the
// warning before the button is pressed must compute the same thing.

export const PROVENANCE_REQUIRED = ['formula_ref', 'formula_version', 'bom_fill_weight_g'];

export const PROVENANCE_LABEL = {
  source_system: 'Source system',
  formula_ref: 'Formula ref',
  formula_version: 'Formula version',
  bom_fill_weight_g: 'BOM fill weight (g)',
  generated_at: 'Generated on',
  generated_by: 'Generated by',
  notes: 'Notes',
};

/** More than this apart and the approver is shown both numbers and must acknowledge. */
export const FILL_TOLERANCE = 0.01;

const blank = (v) => v === null || v === undefined || String(v).trim() === '';
const num = (v) => (blank(v) ? null : (Number.isFinite(Number(v)) ? Number(v) : null));

/** The provenance block of an `nfp_versions` row, as every reader sees it. */
export function provenanceOf(v) {
  const block = {
    source_system: blank(v?.provenance_source) ? 'unknown' : String(v.provenance_source),
    formula_ref: blank(v?.formula_ref) ? null : String(v.formula_ref),
    formula_version: blank(v?.formula_rev) ? null : String(v.formula_rev),
    bom_fill_weight_g: num(v?.bom_fill_weight_g),
    generated_at: blank(v?.provenance_generated_at) ? null : String(v.provenance_generated_at),
    generated_by: blank(v?.provenance_generated_by) ? null : String(v.provenance_generated_by),
    notes: blank(v?.provenance_notes) ? '' : String(v.provenance_notes),
  };
  return block;
}

/** The required fields the block does not carry. Empty = approvable on provenance. */
export function provenanceMissing(block) {
  return PROVENANCE_REQUIRED.filter((k) => block?.[k] === null || block?.[k] === undefined || block?.[k] === '');
}

/**
 * The panel's fill weight against the Catalogue's.
 *
 * `mismatch` when they differ by more than 1% of the Catalogue figure — the
 * gap 33.32 g against 34.86 g (4.4%) would have raised on the day it happened.
 * A missing figure on either side is its own state, never a pass: the check
 * could not run, and the screen says so.
 */
export function fillWeightCheck(bomFillG, catalogueFillG) {
  const bom = num(bomFillG);
  const catalogue = num(catalogueFillG);
  if (bom === null) return { status: 'no_bom', bom, catalogue, diff_pct: null };
  if (catalogue === null || catalogue <= 0) return { status: 'no_catalogue', bom, catalogue, diff_pct: null };
  const diff = Math.abs(bom - catalogue) / catalogue;
  const pct = Math.round(diff * 10000) / 100;
  return { status: diff > FILL_TOLERANCE + 1e-9 ? 'mismatch' : 'ok', bom, catalogue, diff_pct: pct };
}

export function fillCheckSentence(c) {
  if (!c) return '';
  if (c.status === 'mismatch') {
    return `The panel was computed at ${c.bom} g; the Catalogue fill weight is ${c.catalogue} g — `
      + `${c.diff_pct}% apart (more than 1%).`;
  }
  if (c.status === 'no_catalogue') return 'No Catalogue fill weight to check the panel\'s against.';
  if (c.status === 'no_bom') return 'No BOM fill weight recorded on the panel.';
  return `Fill weight agrees with the Catalogue (${c.bom} g against ${c.catalogue} g).`;
}

/**
 * Is the panel still describing the formula the catalogue says is current?
 * Reasons, not a flag: each names the two values that disagree.
 */
export function provenanceStale(block, product) {
  const out = [];
  if (!block || !product) return out;
  const curRef = blank(product.mrp_formula_id) ? null : String(product.mrp_formula_id);
  const curVer = blank(product.formula_rev) ? null : String(product.formula_rev);
  if (block.formula_ref && curRef && block.formula_ref !== curRef) {
    out.push(`Panel computed from ${block.formula_ref}; the catalogue's formula is ${curRef}.`);
  }
  if (block.formula_version && curVer && block.formula_version !== curVer
      && (!block.formula_ref || !curRef || block.formula_ref === curRef)) {
    out.push(`Panel computed from formula version ${block.formula_version}; the current version is ${curVer}.`);
  }
  const fc = fillWeightCheck(block.bom_fill_weight_g, product.fill_weight_g);
  if (fc.status === 'mismatch') out.push(fillCheckSentence(fc));
  return out;
}

/** The one line near the status: `from F-00002 v2.0 @ 88.0g`. Null when nothing is recorded. */
export function provenancePhrase(block) {
  if (!block || provenanceMissing(block).length === PROVENANCE_REQUIRED.length) return null;
  const ref = block.formula_ref || 'formula ?';
  const ver = block.formula_version ? ` ${block.formula_version}` : '';
  const g = block.bom_fill_weight_g !== null && block.bom_fill_weight_g !== undefined
    ? ` @ ${Number(block.bom_fill_weight_g).toFixed(1)}g` : '';
  return `from ${ref}${ver}${g}`;
}
